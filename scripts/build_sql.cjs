const fs = require('fs');
const path = require('path');

const rootDir = path.resolve(__dirname, '..');
const socios = JSON.parse(fs.readFileSync(path.join(rootDir, 'src', 'socios.json'), 'utf8').replace(/^\uFEFF/, ''));
